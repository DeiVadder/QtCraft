#include <algorithm>
#include <utility>

using namespace Qt::StringLiterals;

namespace {

// The region that holds the block column `x`, `z`, clamped to the world.
QcChunkPos regionOfColumn(qint64 x, qint64 z)
{
    const auto clamped = [](qint64 value) {
        return static_cast<int>(std::clamp<qint64>(value, -QcWorld::maxHorizontalBlock, QcWorld::maxHorizontalBlock));
    };
    return QcChunkSet::regionOf(QcBlockPos{clamped(x), 0, clamped(z)}.chunk());
}

// Whether `candidate` lies nearer to `from` than `best` (none yet: always).
bool nearer(QcBlockPos from, QcBlockPos candidate, std::optional<QcBlockPos> best)
{
    return !best || QcPlaceSearch::distance(from, candidate) < QcPlaceSearch::distance(from, *best);
}

} // namespace

QcVersionedGenerator::QcVersionedGenerator(std::unique_ptr<QcWorldGenerator> own)
    : m_base(std::move(own))
{
    QcWorldGenerator::setVersion(base().version());
    m_warnings = base().warnings();
}

QcStatus QcVersionedGenerator::setVersionMap(const QcGeneratorVersionMap &map, const Factory &create)
{
    if (m_generated.load()) {
        return qcError(u"The generator version map can only be set before the first chunk is generated"_s);
    }
    std::vector<Older> found;
    QStringList warnings = base().warnings();
    const QList<int> versions = map.versions();
    for (const int mapped : versions) {
        if (mapped == version()) {
            continue;
        }
        std::unique_ptr<QcWorldGenerator> generator = create(mapped);
        if (!generator) {
            return qcError(u"The chunks of world generator version %1 cannot be generated by this game"_s.arg(mapped));
        }
        warnings.append(generator->warnings());
        found.push_back({mapped, map.chunksOf(mapped), std::move(generator)});
    }
    m_map = map;
    setOlder(std::move(found));
    warnings.removeDuplicates();
    m_warnings = warnings;
    return {};
}

void QcVersionedGenerator::setVersion(int version)
{
    QcWorldGenerator::setVersion(version);
    m_base->setVersion(version);
}

const QcWorldGenerator &QcVersionedGenerator::generatorAt(QcChunkPos pos) const
{
    for (const Older &entry : older()) {
        if (entry.chunks.contains(pos)) {
            return *entry.generator;
        }
    }
    return base();
}

std::vector<const QcWorldGenerator *> QcVersionedGenerator::generatorsNear(QcBlockPos from, int reach) const
{
    std::vector<const QcWorldGenerator *> near{&base()};
    if (older().empty()) {
        return near;
    }
    // A planner looks a region further than its reach: a plan may start in the next region.
    const qint64 margin = qint64{reach} + qint64{QcChunkSet::regionSize} * QcWorld::chunkSize;
    const QcChunkPos lowest = regionOfColumn(from.x - margin, from.z - margin);
    const QcChunkPos highest = regionOfColumn(from.x + margin, from.z + margin);
    for (const Older &entry : older()) {
        if (entry.chunks.hasRegionWithin(lowest, highest)) {
            near.push_back(entry.generator.get());
        }
    }
    return near;
}

std::shared_ptr<QcChunk> QcVersionedGenerator::generate(QcChunkPos pos) const
{
    m_generated.store(true, std::memory_order_relaxed);
    return generatorAt(pos).generate(pos);
}

QString QcVersionedGenerator::biomeAt(int x, int z) const
{
    return generatorAt(QcBlockPos{x, 0, z}.chunk()).biomeAt(x, z);
}

std::shared_ptr<const QcVillagePlan> QcVersionedGenerator::nearestVillage(QcBlockPos from, int reach) const
{
    std::shared_ptr<const QcVillagePlan> best;
    for (const QcWorldGenerator *generator : generatorsNear(from, reach)) {
        std::shared_ptr<const QcVillagePlan> plan = generator->nearestVillage(from, reach);
        if (plan && generates(*generator, plan->centre) && nearer(from, plan->centre, best ? std::optional(best->centre) : std::nullopt)) {
            best = std::move(plan);
        }
    }
    return best;
}

QcStructureSites QcVersionedGenerator::ownSites(const QcWorldGenerator &generator, const QcStructureSites &sites) const
{
    QcStructureSites own;
    std::ranges::copy_if(sites.guards, std::back_inserter(own.guards), [&](const QcGuardSite &site) { return generates(generator, site.min); });
    std::ranges::copy_if(sites.spawnAreas, std::back_inserter(own.spawnAreas),
                         [&](const QcSpawnArea &area) { return generates(generator, area.min); });
    return own;
}

QcStructureSites QcVersionedGenerator::structureSitesNear(QcBlockPos from, int reach) const
{
    if (older().empty()) {
        return base().structureSitesNear(from, reach);
    }
    QcStructureSites sites;
    for (const QcWorldGenerator *generator : generatorsNear(from, reach)) {
        sites.add(ownSites(*generator, generator->structureSitesNear(from, reach)));
    }
    return sites;
}

std::optional<QcStructureSites> QcVersionedGenerator::plannedStructureSitesNear(QcBlockPos from, int reach) const
{
    if (older().empty()) {
        return base().plannedStructureSitesNear(from, reach);
    }
    QcStructureSites sites;
    for (const QcWorldGenerator *generator : generatorsNear(from, reach)) {
        const std::optional<QcStructureSites> planned = generator->plannedStructureSitesNear(from, reach);
        if (!planned) {
            return std::nullopt;
        }
        sites.add(ownSites(*generator, *planned));
    }
    return sites;
}

std::optional<QcStructurePlacement> QcVersionedGenerator::nearestStructure(const QString &name, QcBlockPos from, int reach) const
{
    std::optional<QcStructurePlacement> best;
    for (const QcWorldGenerator *generator : generatorsNear(from, reach)) {
        std::optional<QcStructurePlacement> found = generator->nearestStructure(name, from, reach);
        if (found && generates(*generator, found->origin()) && nearer(from, found->origin(), best ? std::optional(best->origin()) : std::nullopt)) {
            best = std::move(found);
        }
    }
    return best;
}

QcLocateResult QcVersionedGenerator::locate(QStringView kind, QcBlockPos from, int reach) const
{
    if (older().empty()) {
        return base().locate(kind, from, reach);
    }
    QcLocateResult best{std::nullopt, reach};
    for (const QcWorldGenerator *generator : generatorsNear(from, reach)) {
        const QcLocateResult found = generator->locate(kind, from, reach);
        best.searched = std::min(best.searched, found.searched);
        const std::optional<QcBlockPos> bestAt = best.place ? std::optional(best.place->at) : std::nullopt;
        if (found.place && generates(*generator, found.place->at) && nearer(from, found.place->at, bestAt)) {
            best.place = found.place;
        }
    }
    return best;
}
