#pragma once

#include "common/core/QcResult.h"
#include "common/world/QcChunkSet.h"
#include "common/world/QcGeneratorVersionMap.h"
#include "worldgen/generators/QcWorldGenerator.h"

#include <atomic>
#include <functional>
#include <memory>
#include <vector>

/*! \brief The generator of a dimension that generates each chunk with the generator version a
    version map gives it (decision E-1012): the chunks of a world switched to a newer version that
    were explored before keep their older version, the rest is generated by the dimension's own
    generator (the base).

    Without a map it only passes everything on to the base. Questions about one chunk or column
    go to the generator of its version; searches over regions (villages, structures, guardian
    zones, /locate) ask every generator with chunks near the place and keep what each finds in
    its own chunks (a village by its centre, a structure by its origin, a zone or spawn area by
    its lowest corner), the nearest one for searches. Each generator builds only the structures
    whose reach lies wholly in its own chunks (decision E-1013,
    QcWorldGenerator::setStructureFilter): a structure is built whole by one version or not at
    all, and the searches of each generator skip the others' (so a nearer one in foreign chunks
    never hides a farther own one). The spawn point is that of the origin's generator. The rest
    (the one-time setup, the platform and the words of /locate) is the base's. version() is the
    base's: the dimension's version in world.json. Safe to call from several threads once the map
    is set. */
class QcVersionedGenerator final : public QcWorldGenerator
{
public:
    /*! Makes a generator of \a version, nullptr when this game does not generate it. */
    using Factory = std::function<std::unique_ptr<QcWorldGenerator>(int version)>;

    /*! Generates everything with \a own, the dimension's own generator, until setVersionMap()
        is called. */
    explicit QcVersionedGenerator(std::unique_ptr<QcWorldGenerator> own);

    /*! Generates the chunks \a map names with generators of their versions, made by \a create
        (the base for its own version), each building only the structures wholly in its chunks.
        Only before the first chunk is generated: returns an error then, and when \a create
        makes no generator for a version; the map stays as it was on error. */
    [[nodiscard]] QcStatus setVersionMap(const QcGeneratorVersionMap &map, const Factory &create);
    /*! Returns the version map the generator follows (empty: everything is the base's). */
    const QcGeneratorVersionMap &versionMap() const { return m_map; }
    /*! Returns the dimension's own generator. */
    const QcWorldGenerator &base() const { return *m_base; }

    std::shared_ptr<QcChunk> generate(QcChunkPos pos) const override;
    /*! Returns the spawn point of the generator of the origin's chunk: a world's origin is always
        explored, so the spawn stays where it was after a switch (decision E-1012). */
    QcBlockPos spawnPoint() const override { return generatorAt(QcChunkPos{0, 0}).spawnPoint(); }
    QString biomeAt(int x, int z) const override;
    bool isNaturalGround(QcBlockId block) const override { return base().isNaturalGround(block); }
    [[nodiscard]] std::optional<QcBlockId> platformBlock() const override { return base().platformBlock(); }
    QcWorldSetup setup() const override { return base().setup(); }
    [[nodiscard]] std::shared_ptr<const QcVillagePlan> villageFor(QcChunkPos pos) const override { return generatorAt(pos).villageFor(pos); }
    [[nodiscard]] std::shared_ptr<const QcVillagePlan> nearestVillage(QcBlockPos from, int reach) const override;
    QList<QcBlockPos> pointsOfInterestIn(QcChunkPos pos) const override { return generatorAt(pos).pointsOfInterestIn(pos); }
    QcChunkFurnishing furnishingIn(QcChunkPos pos) const override { return generatorAt(pos).furnishingIn(pos); }
    QcStructureSites structureSitesNear(QcBlockPos from, int reach) const override;
    [[nodiscard]] std::optional<QcStructureSites> plannedStructureSitesNear(QcBlockPos from, int reach) const override;
    [[nodiscard]] std::optional<QcStructurePlacement> nearestStructure(const QString &name, QcBlockPos from, int reach) const override;
    QStringList locatableNames() const override { return base().locatableNames(); }
    [[nodiscard]] QcLocateResult locate(QStringView kind, QcBlockPos from, int reach) const override;
    QList<QcWorldLabel> labelsIn(QcChunkPos pos) const override { return generatorAt(pos).labelsIn(pos); }
    /*! Returns the structures the generator of the chunk \a pos builds into it. */
    [[nodiscard]] QList<QcXzRect> structuresTouching(QcChunkPos pos) const override { return generatorAt(pos).structuresTouching(pos); }
    void setVersion(int version) override;

private:
    // A generator of an older version and the chunks it generates.
    struct Older
    {
        int version = 0;
        QcChunkSet chunks;
        std::unique_ptr<QcWorldGenerator> generator;
    };

    // The generators of the older versions in the map.
    const std::vector<Older> &older() const { return m_older; }
    void setOlder(std::vector<Older> older) { m_older = std::move(older); }
    // The generator of the chunk `pos`.
    const QcWorldGenerator &generatorAt(QcChunkPos pos) const;
    // Whether `generator` generates the chunk that holds `pos`.
    bool generates(const QcWorldGenerator &generator, QcBlockPos pos) const { return &generatorAt(pos.chunk()) == &generator; }
    // The generators with chunks within `reach` blocks of `from`: the base first.
    std::vector<const QcWorldGenerator *> generatorsNear(QcBlockPos from, int reach) const;
    // Lets each generator build only the structures wholly in its own chunks.
    void filterStructures();
    // What `generator` found of `sites` in its own chunks.
    QcStructureSites ownSites(const QcWorldGenerator &generator, const QcStructureSites &sites) const;

    std::unique_ptr<QcWorldGenerator> m_base;
    QcGeneratorVersionMap m_map;
    std::vector<Older> m_older;
    // Set by the first generate(): the map may no longer change.
    mutable std::atomic<bool> m_generated{false};
};
