constexpr int columns = 5;
constexpr int baseTile = QcPixelFont::cellSize * QcPixelFont::cellsPerRow;

// The glyph index of each character and the columns each glyph covers, worked out once.
struct Table
{
    QHash<char32_t, int> index;
    std::array<QcPixelFont::Glyph, std::size(bitmaps)> glyphs{};

    Table()
    {
        for (std::size_t i = 0; i < std::size(bitmaps); ++i) {
            index.insert(bitmaps[i].character, int(i));
            glyphs[i] = glyphOf(bitmaps[i], int(i));
        }
    }

    // Where glyph `i` lies and which columns of it have pixels.
    static QcPixelFont::Glyph glyphOf(Bitmap bitmap, int i)
    {
        int first = columns;
        int last = -1;
        for (int column = 0; column < columns; ++column) {
            const auto bit = quint8(1U << unsigned(columns - 1 - column));
            if (std::ranges::any_of(bitmap.rows, [bit](quint8 row) { return (row & bit) != 0; })) {
                first = std::min(first, column);
                last = column;
            }
        }
        return {i / QcPixelFont::glyphsPerPage, i % QcPixelFont::glyphsPerPage, last < 0 ? 0 : first, last < 0 ? 0 : last - first + 1};
    }
};

const Table &table()
{
    static const Table built;
    return built;
}

// The pixels of `bitmap` in white on a transparent cell.
QImage glyphImage(Bitmap bitmap)
{
    QImage image(QcPixelFont::cellSize, QcPixelFont::cellSize, QImage::Format_RGBA8888);
    image.fill(Qt::transparent);
    for (int row = 0; row < QcPixelFont::glyphHeight; ++row) {
        for (int column = 0; column < columns; ++column) {
            if ((bitmap.rows[std::size_t(row)] & (1U << unsigned(columns - 1 - column))) != 0) {
                image.setPixelColor(column, row, Qt::white);
            }
        }
    }
    return image;
}

